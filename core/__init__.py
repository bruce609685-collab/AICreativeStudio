"""核心服务层（headless，禁止 import PySide6）。

这个包是整个应用的"后台大脑"，负责所有与界面无关的核心逻辑。
之所以叫 headless（无头），是因为它完全不依赖任何图形界面库——
这样既可以让界面层（PySide6）随便换、随便改，也方便在命令行下
单独测试这些功能。

本包内含三个子包，各司其职：
- registry（脚本注册表）：扫描 scripts/ 目录，读取脚本头部的
  ACS_META 注释块，把每个脚本登记成一张"节目单"，供界面查询展示。
- runner（脚本执行器）：负责真正跑脚本——组装参数、启动子进程、
  隔离执行、回传结果，相当于"放映员"。
- importer（智能导入）：用户丢进一份 API 文档后，由 LLM 自动
  生成一个符合规范的脚本并注册进注册表，相当于"新节目自动上架"。

M2 起填充；M1 仅建骨架。各包职责见 __init__ 注释。
"""
